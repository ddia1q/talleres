create table if not exists public.domi_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  display_name text,
  role text not null default 'CHOFER' check (role in ('ADMIN','CHOFER')),
  created_at timestamptz not null default now()
);

create table if not exists public.domi_route_stops (
  id bigint generated by default as identity primary key,
  driver_id uuid not null references public.domi_profiles(id) on delete cascade,
  route_date date not null default (now() at time zone 'America/Mexico_City')::date,
  place_id text not null,
  name text not null,
  address text not null default '',
  lat double precision,
  lng double precision,
  phone text not null default '',
  visited boolean not null default false,
  created_at timestamptz not null default now(),
  unique(driver_id, route_date, place_id)
);

create table if not exists public.domi_visits (
  id bigint generated by default as identity primary key,
  driver_id uuid not null references public.domi_profiles(id) on delete cascade,
  place_id text not null,
  place_name text not null,
  contact text not null default '',
  attended_by text not null,
  interested text not null default 'pendiente' check (interested in ('si','no','pendiente')),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists domi_route_driver_date_idx on public.domi_route_stops(driver_id, route_date);
create index if not exists domi_visits_driver_created_idx on public.domi_visits(driver_id, created_at desc);

-- Perfil automático para cada usuario que se crea en Authentication.
create or replace function public.domi_new_user_profile()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.domi_profiles (id, email, display_name, role)
  values (new.id, coalesce(new.email,''), coalesce(new.raw_user_meta_data->>'display_name', new.email), 'CHOFER')
  on conflict (id) do update set email = excluded.email;
  return new;
end;
$$;
drop trigger if exists domi_auth_user_created on auth.users;
create trigger domi_auth_user_created after insert on auth.users
for each row execute procedure public.domi_new_user_profile();

-- SECURITY DEFINER evita recursión de políticas al revisar el rol.
create or replace function public.domi_is_admin()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists(select 1 from public.domi_profiles p where p.id = (select auth.uid()) and p.role = 'ADMIN');
$$;
revoke all on function public.domi_is_admin() from public;
grant execute on function public.domi_is_admin() to authenticated;

alter table public.domi_profiles enable row level security;
alter table public.domi_route_stops enable row level security;
alter table public.domi_visits enable row level security;

drop policy if exists "profile own or admin read" on public.domi_profiles;
create policy "profile own or admin read" on public.domi_profiles for select to authenticated
using (id = (select auth.uid()) or public.domi_is_admin());
drop policy if exists "admin manage profiles" on public.domi_profiles;
create policy "admin manage profiles" on public.domi_profiles for update to authenticated
using (public.domi_is_admin()) with check (public.domi_is_admin());

-- Cada chofer solo ve y modifica su propia ruta. ADMIN puede consultar todas.
drop policy if exists "route own or admin read" on public.domi_route_stops;
create policy "route own or admin read" on public.domi_route_stops for select to authenticated
using (driver_id = (select auth.uid()) or public.domi_is_admin());
drop policy if exists "route own insert" on public.domi_route_stops;
create policy "route own insert" on public.domi_route_stops for insert to authenticated
with check (driver_id = (select auth.uid()));
drop policy if exists "route own update" on public.domi_route_stops;
create policy "route own update" on public.domi_route_stops for update to authenticated
using (driver_id = (select auth.uid())) with check (driver_id = (select auth.uid()));
drop policy if exists "route own delete" on public.domi_route_stops;
create policy "route own delete" on public.domi_route_stops for delete to authenticated
using (driver_id = (select auth.uid()));

-- Un chofer solo inserta/lee sus visitas. Solo ADMIN consulta el historial global.
drop policy if exists "visits own insert" on public.domi_visits;
create policy "visits own insert" on public.domi_visits for insert to authenticated
with check (driver_id = (select auth.uid()));
drop policy if exists "visits own or admin read" on public.domi_visits;
create policy "visits own or admin read" on public.domi_visits for select to authenticated
using (driver_id = (select auth.uid()) or public.domi_is_admin());

-- Grants para la API pública autenticada; RLS sigue limitando cada fila.
grant usage on schema public to authenticated;
grant select on public.domi_profiles to authenticated;
grant update (display_name, role) on public.domi_profiles to authenticated;
grant select, insert, update, delete on public.domi_route_stops to authenticated;
grant select, insert on public.domi_visits to authenticated;
grant usage, select on all sequences in schema public to authenticated;
